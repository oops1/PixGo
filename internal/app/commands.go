package app

import (
	"github.com/oops1/PixGo/internal/commands"
)

func (a *App) registerCommands() {
	img := a.hasImage
	run := map[commands.ID]func(){
		CmdPrev:            func() { a.Ctl.Step(-1) },
		CmdNext:            func() { a.Ctl.Step(1) },
		CmdFirst:           func() { a.Ctl.First() },
		CmdLast:            func() { a.Ctl.Last() },
		CmdZoomIn:          a.or3D(a.Canvas.ZoomIn, a.View3D.ZoomIn),
		CmdZoomOut:         a.or3D(a.Canvas.ZoomOut, a.View3D.ZoomOut),
		CmdZoomActual:      a.or3D(a.Canvas.Actual, a.View3D.Reset),
		CmdZoomFit:         a.or3D(a.Canvas.Fit, a.View3D.Reset),
		CmdZoomWidth:       a.Canvas.FitWidth,
		CmdZoomToggle:      a.or3D(a.Canvas.ToggleFitActual, a.View3D.Reset),
		CmdRotateRight:     a.rotateOrEdit(true, a.or3D(a.Canvas.RotateRight, func() { a.View3D.Turn(true) })),
		CmdRotateLeft:      a.rotateOrEdit(false, a.or3D(a.Canvas.RotateLeft, func() { a.View3D.Turn(false) })),
		CmdRotate180:       a.rotate180OrEdit,
		CmdFlipH:           a.flipOrEdit(true, a.Canvas.FlipH),
		CmdFlipV:           a.flipOrEdit(false, a.Canvas.FlipV),
		CmdFavorite:        func() { a.Ctl.ToggleFavorite() },
		CmdOpen:            a.OpenGallery,
		CmdGallery:         a.OpenGallery,
		CmdBack:            a.OpenGallery,
		CmdSettings:        a.OpenSettings,
		CmdDelete:          func() { a.deleteCurrent(false) },
		CmdDeletePermanent: func() { a.deleteCurrent(true) },
		CmdCopy:            a.copyFile,
		CmdCopyPath:        a.copyPath,
		CmdCopyImage:       a.copyImage,
		CmdReveal:          a.reveal,
		CmdSaveAs:          a.saveAs,
		CmdPrint:           a.printPicture,
		CmdExportPDF:       a.exportPDF,
		CmdFullscreen:      a.toggleFullscreen,
		CmdSlideshow:       a.toggleSlideshow,
		CmdSlideshowToggle: a.toggleSlideshowPause,
		CmdInfo:            a.toggleInfo,
		CmdEscape:          a.escape,
		CmdCheckUpdates:    a.CheckForUpdates,
		CmdEditStart:       a.startEdit,
		CmdCrop:            a.startEdit,
		CmdResize:          a.startResize,
		CmdView3D:          a.toggleView3D,
	}
	enabled := map[commands.ID]func() bool{
		CmdPrev:            a.CanPrev,
		CmdNext:            a.CanNext,
		CmdFirst:           a.CanPrev,
		CmdLast:            a.CanNext,
		CmdZoomIn:          img,
		CmdZoomOut:         img,
		CmdZoomActual:      img,
		CmdZoomFit:         img,
		CmdZoomWidth:       img,
		CmdZoomToggle:      img,
		CmdRotateRight:     img,
		CmdRotateLeft:      img,
		CmdRotate180:       img,
		CmdFlipH:           img,
		CmdFlipV:           img,
		CmdFavorite:        img,
		CmdDelete:          a.hasFile,
		CmdDeletePermanent: a.hasFile,
		CmdCopy:            a.hasFile,
		CmdCopyPath:        a.hasFile,
		CmdCopyImage:       img,
		CmdReveal:          a.hasFile,
		CmdSaveAs:          img,
		CmdPrint:           a.canPrint,
		CmdExportPDF:       a.canPrint,
		CmdFullscreen:      img,
		CmdInfo:            a.hasFile,
		CmdSlideshow:       a.canSlideshow,
		CmdSlideshowToggle: a.canSlideshow,
		CmdEscape:          func() bool { return a.fullscreen || a.slideshowActive() || a.infoOpen || a.m3d.active },
		CmdEditStart:       a.canStartEdit,
		CmdCrop:            a.canStartEdit,
		CmdResize:          a.canStartEdit,
		CmdView3D:          a.canView3D,
	}
	for _, s := range Specs {
		a.Commands.Add(commands.Command{
			ID:      s.ID,
			Title:   s.Title,
			Icon:    s.Icon,
			Keys:    s.Keys,
			Run:     run[s.ID],
			Enabled: a.gateEnabled(s.ID, enabled[s.ID]),
		})
	}
}
